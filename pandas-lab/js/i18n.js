  /* 取值：t('nav.load') */
  t(key, vars) {
    const parts = String(key).split('.');
    let v = this.dict[this.lang];
    for (const p of parts) {
      if (v == null) return key;
      v = v[p];
    }
    if (v == null) return key;
    if (vars) {
      return String(v).replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ''));
    }
    return v;
  },
  set(lang) { this.lang = lang; },
  toggle() { this.lang = this.lang === 'zh' ? 'en' : 'zh'; return this.lang; },
